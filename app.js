  var lastSpread = -1;

  function overviewWidth() {
    var pad = 1.12;
    var w = (bounds.x1 - bounds.x0) * pad;
    var h = (bounds.y1 - bounds.y0) * pad;
    var ratio = svg.clientHeight / svg.clientWidth || 0.6;
    return Math.max(w, h / ratio);
  }
  function overview() {
    return {
      cx: (bounds.x0 + bounds.x1) / 2,
      cy: (bounds.y0 + bounds.y1) / 2,
      w: overviewWidth()
    };
  }

  function dotR(id) {
    var base = STATIONS[id].lines.length > 1 ? 3.6 : 2.5;
    if (id === current) base = 4.6;
    return base * unitsPerPx;
  }

  function applyCam() {
    var cw = svg.clientWidth || 1, ch = svg.clientHeight || 1;
    var h = view.w * ch / cw;
    svg.setAttribute('viewBox',
      (view.cx - view.w / 2) + ' ' + (view.cy - h / 2) + ' ' + view.w + ' ' + h);
    unitsPerPx = view.w / cw;

    var spread = 3.1 * unitsPerPx;
    if (lastSpread < 0 || Math.abs(spread - lastSpread) / lastSpread > 0.004) {
      lastSpread = spread;
      geomList.forEach(function (g) { g.el.setAttribute('d', edgePath(g, spread)); });
      routeParts.forEach(function (rp) {
        var ride = ridePath(rp.g, spread, rp.forward);
        rp.plan.setAttribute('d', edgePath(rp.g, spread));
        rp.done.setAttribute('d', pathFrom(ride));
        rp.len = polyLength(ride);
      });
      ids.forEach(function (id) { dots[id].setAttribute('r', dotR(id)); });
      gLabels.style.fontSize = (11.5 * unitsPerPx) + 'px';
      gLabels.style.strokeWidth = (2.6 * unitsPerPx) + 'px';
    }
    placeTrain();          /* cheap, and it moves on every frame of a journey */
    placeLabels();
  }

  function tweenTo(target, ms, done) {
    var from = { cx: view.cx, cy: view.cy, w: view.w };
    var t0 = performance.now();
    anim = function (now) {
      var p = Math.min(1, (now - t0) / ms);
      var e = p < 0.5 ? 4 * p * p * p : 1 - Math.pow(-2 * p + 2, 3) / 2;
      view.cx = from.cx + (target.cx - from.cx) * e;
      view.cy = from.cy + (target.cy - from.cy) * e;
      /* interpolate zoom geometrically so it feels linear to the eye */
      view.w = from.w * Math.pow(target.w / from.w, e);
      applyCam();
      if (p >= 1) { anim = null; if (done) done(); }
    };
  }

  var frameJobs = [];
  function loop(now) {
    if (anim) anim(now);
    for (var i = frameJobs.length - 1; i >= 0; i--) {
      if (frameJobs[i](now) === false) frameJobs.splice(i, 1);
    }
    requestAnimationFrame(loop);
  }
  requestAnimationFrame(loop);

