  function showJourney(from, to, steps) {
    if (!journeyBox) return;
    if (!steps || !steps.length) { journeyBox.hidden = true; return; }
    var ls = legs(steps);
    var mins = steps.reduce(function (a, s) { return a + s.t; }, 0) +
               (ls.length - 1) * 2;
    var html = '<div class="jt">' + esc(STATIONS[from].name) + ' &rarr; ' +
      esc(STATIONS[to].name) + '</div>';
    ls.forEach(function (l) {
      var L = lineInfo(l.line);
      html += '<div class="leg">' +
        '<span class="bar" style="background:' + L.colour + '"></span>' +
        '<span class="leg-txt">' +
        (l.line === 'walk'
          ? 'Walk to <b>' + esc(STATIONS[l.to].name) + '</b>'
          : '<b>' + esc(L.name) + '</b> to ' + esc(STATIONS[l.to].name) +
            ' &middot; ' + l.stops + ' stop' + (l.stops > 1 ? 's' : '')) +
        '</span></div>';
    });
    html += '<div class="foot">' + (ls.length - 1) + ' change' +
      (ls.length - 1 === 1 ? '' : 's') + ' &middot; about ' + Math.round(mins) +
      ' min</div>';
    journeyBox.innerHTML = html;
    journeyBox.hidden = false;
  }

