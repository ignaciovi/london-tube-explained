  function filter(q) {
    var n = norm(q);
    if (!n) return order.slice(0, 40);
    var starts = [], words = [], contains = [];
    ids.forEach(function (id) {
      var nm = normNames[id];
      var at = nm.indexOf(n);
      if (at === 0) starts.push(id);
      else if (at > 0 && nm[at - 1] === ' ') words.push(id);
      else if (at > 0) contains.push(id);
    });
    function byName(a, b) { return STATIONS[a].name < STATIONS[b].name ? -1 : 1; }
    return starts.sort(byName).concat(words.sort(byName), contains.sort(byName)).slice(0, 40);
  }

  function moveCursor(d) {
    if (!shown.length) return;
    cursor = (cursor + d + shown.length) % shown.length;
    Array.prototype.forEach.call(results.children, function (li, i) {
      li.setAttribute('aria-selected', i === cursor);
      if (i === cursor) li.scrollIntoView({ block: 'nearest' });
    });
  }

