  var layoutBtn = document.getElementById('btn-layout');
  var morphing = false;

  function setLayout(mode) {
    if (mode === layoutMode || morphing) return;
    morphing = true;
    if (running) { frameJobs.length = 0; running = null; endTravelStyling(); }
    clearRoute();
    if (journeyBox) journeyBox.hidden = true;

    var from = {}, to = LAYOUTS[mode];
    ids.forEach(function (id) { from[id] = { x: P[id].x, y: P[id].y }; });

    var wasOverview = view.w > overviewWidth() * 0.75;
    var anchor = wasOverview ? null : current;
    var targetW = wasOverview ? null : LAYOUT_STEP[mode] * STATION_ZOOM[mode];
    var w0 = view.w;
    var t0 = performance.now(), ms = 1600;
    layoutMode = mode;
    stationW = LAYOUT_STEP[mode] * STATION_ZOOM[mode];
    layoutBtn.textContent = mode === 'schematic' ? 'Geographic' : 'Schematic';
    anim = null;

    frameJobs.push(function (now) {
      var p = Math.min(1, (now - t0) / ms);
      var e = p < 0.5 ? 4 * p * p * p : 1 - Math.pow(-2 * p + 2, 3) / 2;
      ids.forEach(function (id) {
        P[id].x = from[id].x + (to[id].x - from[id].x) * e;
        P[id].y = from[id].y + (to[id].y - from[id].y) * e;
        dots[id].setAttribute('cx', P[id].x);
        dots[id].setAttribute('cy', P[id].y);
      });
      /* straight edges while things are moving; proper routing once settled */
      buildGeometry(p >= 1 && mode === 'schematic');
      drawTransfers();
      bounds = computeBounds();
      lastSpread = -1;                       // force the edges to be redrawn

      if (anchor) {
        view.cx = P[anchor].x; view.cy = P[anchor].y;
        view.w = w0 * Math.pow(targetW / w0, e);
        parkTrain(anchor);          /* the train rides the move too */
      } else {
        var ov = overview();
        view.cx = ov.cx; view.cy = ov.cy; view.w = ov.w;
      }
      applyCam();
      if (p >= 1) {
        if (anchor) parkTrain(anchor);
        morphing = false;
        return false;
      }
      return true;
    });
  }

