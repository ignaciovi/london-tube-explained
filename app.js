  function drawRoute(steps) {
    clearRoute();
    steps.forEach(function (s) {
      var g = geom[s.from + '|' + s.to + '|' + s.line];
      if (!g) {
        /* a walking transfer: straight, no fan-out */
        g = { a: s.from, b: s.to, off: 0, line: s.line,
              pts: [[P[s.from].x, P[s.from].y], [P[s.to].x, P[s.to].y]] };
      }
      var colour = lineInfo(s.line).colour;
      var plan = el('path', {
        'class': 'route-leg', stroke: colour,
        'vector-effect': 'non-scaling-stroke', 'stroke-width': 7,
        d: edgePath(g, lastSpread)
      });
      var forward = s.from === g.a;
      var ride = ridePath(g, lastSpread, forward);
      var done = el('path', {
        'class': 'route-leg done', stroke: colour,
        'vector-effect': 'non-scaling-stroke', 'stroke-width': 7,
        d: pathFrom(ride)
      });
      done.style.strokeDasharray = '0 100000';
      gPlan.appendChild(plan);
      gDone.appendChild(done);
      routeParts.push({
        g: g, plan: plan, done: done, forward: forward, len: polyLength(ride)
      });
      dots[s.from].classList.add('on-route');
      dots[s.to].classList.add('on-route');
    });
  }

  function travel(steps, arrive) {
    var total = steps.reduce(function (a, s) { return a + s.t; }, 0);
    var ms = Math.max(2000, Math.min(14000, 520 * steps.length + 900));
    var t0 = performance.now();
    markInvolved(steps);
    gEdges.classList.add('muted');

    var travelW = Math.min(overviewWidth() * 0.75,
                           stationW * (1.6 + 0.9 * Math.sqrt(steps.length)));

    running = function (now) {
      var p = Math.min(1, (now - t0) / ms);
      var e = p < 0.5 ? 2 * p * p : 1 - Math.pow(-2 * p + 2, 2) / 2;

      /* find the step we are on, weighted by scheduled minutes */
      var travelled = e * total, acc = 0, i = 0, frac = 0;
      for (i = 0; i < steps.length; i++) {
        if (acc + steps[i].t >= travelled || i === steps.length - 1) {
          frac = Math.min(1, (travelled - acc) / steps[i].t);
          break;
        }
        acc += steps[i].t;
      }

      whereTrainIs = frac > 0.5 ? steps[i].to : steps[i].from;
      var rpNow = routeParts[i];
      var at = walk(ridePath(rpNow.g, lastSpread, rpNow.forward), frac);
      var x = at.x, y = at.y;
      trainPos = { x: x, y: y, angle: at.angle };

      for (var j = 0; j < routeParts.length; j++) {
        var rp = routeParts[j];
        var f = j < i ? 1 : j > i ? 0 : frac;
        rp.done.style.strokeDasharray = (rp.len * f) + ' 100000';
      }

      /* camera: pull back for the ride, close in on arrival */
      var w;
      if (p < 0.12) w = view.w * Math.pow(travelW / view.w, p / 0.12);
      else if (p > 0.86) {
        var q = (p - 0.86) / 0.14;
        w = travelW * Math.pow(stationW / travelW, q);
      } else w = travelW;

      view.cx = x; view.cy = y; view.w = w;
      applyCam();

      if (p >= 1) {
        running = null;
        endTravelStyling();
        arrive();
        return false;
      }
      return true;
    };
    frameJobs.push(running);
  }

